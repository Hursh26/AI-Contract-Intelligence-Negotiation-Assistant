import { useEffect, useMemo, useState } from 'react'
import { useLocation } from 'react-router-dom'
import { useContract } from './ContractLayout'
import { Marked, RiskTag, Roll, riskBar } from '../components/ui'

type Decision = 'accepted' | 'rejected'

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

export default function Negotiate() {
  const { contract, analysis: a } = useContract()
  const { hash } = useLocation()
  const key = `fineprint.neg.${contract.id}`
  const changes = useMemo(() => a.clauses.filter((c) => !/^no change/i.test(c.suggestion)), [a])
  const [dec, setDec] = useState<Record<string, Decision>>(() => {
    try {
      return JSON.parse(sessionStorage.getItem(key) ?? '{}')
    } catch {
      return {}
    }
  })
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    try { sessionStorage.setItem(key, JSON.stringify(dec)) } catch { /* storage unavailable */ }
  }, [dec, key])
  useEffect(() => {
    if (hash) document.getElementById(hash.slice(1))?.scrollIntoView({ behavior: 'smooth', block: 'start' })
  }, [hash])

  const set = (id: string, d: Decision) => setDec((s) => {
    const next = { ...s }
    if (next[id] === d) delete next[id]
    else next[id] = d
    return next
  })
  const accepted = changes.filter((c) => dec[c.id] === 'accepted')
  const rejected = changes.filter((c) => dec[c.id] === 'rejected').length
  const pending = changes.length - accepted.length - rejected

  const email = accepted.length
    ? `Hi,\n\nThanks for sending the agreement. Before I sign, I would like to propose a few changes:\n\n${accepted.map((c) => `• Clause ${c.num} (${c.title}): ${c.ask}`).join('\n')}\n\nHappy to talk through any of these.\n\nBest regards`
    : ''

  async function copy() {
    try {
      await navigator.clipboard.writeText(email)
      setCopied(true)
      setTimeout(() => setCopied(false), 1800)
    } catch {
      window.prompt('Copy your email:', email)
    }
  }

  function download() {
    const body = accepted
      .map((c) => `<h2>Clause ${c.num}: ${esc(c.title)}</h2><p><del style="color:#c22a12">${esc(c.text)}</del></p><p><ins style="background:#d4ff3a;text-decoration:underline">${esc(c.suggestion)}</ins></p>`)
      .join('')
    const html = `<!doctype html><meta charset="utf-8"><title>Marked-up copy</title><body style="font-family:Georgia,serif;max-width:720px;margin:40px auto;line-height:1.6"><h1>Proposed changes: ${esc(contract.filename)}</h1>${body}<p style="color:#666;font-size:12px">Generated by Fineprint. Information only, not legal advice.</p></body>`
    const url = URL.createObjectURL(new Blob([html], { type: 'text/html' }))
    const link = document.createElement('a')
    link.href = url
    link.download = `marked-up-${contract.filename.replace(/\.[^.]+$/, '')}.html`
    link.click()
    URL.revokeObjectURL(url)
  }

  return (
    <main className="mx-auto grid max-w-[1400px] grid-cols-[minmax(0,1fr)] gap-12 px-4 pb-28 pt-10 sm:px-6 md:px-10 lg:grid-cols-[minmax(0,1fr)_400px]">
      <section>
        <p className="mono text-mute">03 · Negotiate</p>
        <h1 className="display mt-4 text-[clamp(40px,6vw,96px)]">What to ask <mark className="hl in">for</mark></h1>
        <p className="mono mt-6 text-mute" aria-live="polite">{accepted.length} accepted · {rejected} dropped · {pending} to decide</p>
        <p className="mt-3 max-w-xl text-lg leading-snug"><Marked text="Nothing is final until **you accept it**. Each change shows why we suggest it." /></p>

        {changes.length === 0 && <p className="mono mt-12 border-2 border-ink p-6">Nothing to renegotiate. We did not find clauses that need changes.</p>}

        <div className="mt-12 space-y-8">
          {changes.map((c) => {
            const d = dec[c.id]
            return (
              <article
                id={c.id}
                key={c.id}
                className="relative scroll-mt-40 border-2 border-ink bg-sheet p-6 transition-opacity duration-300 md:p-8"
                style={{ borderLeft: `10px solid ${d === 'accepted' ? '#0f110e' : riskBar[c.risk]}`, opacity: d === 'rejected' ? 0.55 : 1, boxShadow: d === 'accepted' ? '8px 8px 0 #d4ff3a, 8px 8px 0 2px #0f110e' : '6px 6px 0 #0f110e' }}
              >
                {d === 'accepted' && <span className="stamp absolute right-4 top-4 text-[16px] text-ink max-sm:static max-sm:mb-4 sm:right-6 sm:top-6 sm:text-[18px]" aria-hidden>Agreed</span>}
                {d === 'rejected' && <span className="stamp absolute right-4 top-4 text-[16px] text-mute max-sm:static max-sm:mb-4 sm:right-6 sm:top-6 sm:text-[18px]" aria-hidden>Dropped</span>}
                <div className="flex flex-wrap items-center gap-3">
                  <RiskTag risk={c.risk} />
                  <span className="mono text-mute">{c.risk === 'high' ? 'Must-have' : 'Nice to have'}</span>
                </div>
                <h2 className="display mt-3 text-[clamp(26px,3vw,44px)]">Clause {c.num} · {c.title}</h2>
                <p className="doc-p mt-5">
                  <span className="bg-pen/15 text-pen-d line-through decoration-2">{c.text}</span>
                </p>
                <p className="doc-p mt-3">
                  <span className="bg-lime underline decoration-2 underline-offset-4">{c.suggestion}</span>
                </p>
                <p className="mt-4 text-[16px] leading-snug text-ink/80"><b>Why:</b> {c.why}</p>
                <div className="mt-6 flex flex-wrap gap-4">
                  <button className="btn" aria-pressed={d === 'accepted'} onClick={() => set(c.id, 'accepted')} data-cursor="">
                    <Roll>{d === 'accepted' ? 'Accepted ✓' : 'Accept'}</Roll>
                  </button>
                  <button className="btn btn--light" aria-pressed={d === 'rejected'} onClick={() => set(c.id, 'rejected')} data-cursor="">
                    <Roll>{d === 'rejected' ? 'Dropped' : 'Drop it'}</Roll>
                  </button>
                </div>
              </article>
            )
          })}
        </div>
      </section>

      <aside className="flex flex-col gap-6 lg:sticky lg:top-[84px] lg:max-h-[calc(100vh-100px)] lg:self-start lg:overflow-auto no-sb" aria-label="Email and export">
        <div className="border-2 border-ink bg-ink p-6 text-paper">
          <p className="mono text-lime">Email to the other side</p>
          <pre className={`mt-4 whitespace-pre-wrap font-mono text-[13px] leading-relaxed ${email ? 'caret' : 'text-paper/50'}`} aria-live="polite">
            {email || 'Accept a change and your draft appears here.'}
          </pre>
          <button className="btn mt-6 w-full justify-between" disabled={!email} onClick={copy}>
            <Roll>{copied ? 'Copied ✓' : 'Copy email'}</Roll><span aria-hidden>⧉</span>
          </button>
        </div>
        <div className="border-2 border-ink bg-sheet p-6">
          <p className="mono text-mute">Export</p>
          <p className="mt-2 text-[15px] leading-snug">A copy of your contract showing only the changes you accepted. Old wording is crossed out and new wording is underlined.</p>
          <button className="btn btn--ink mt-5 w-full justify-between" disabled={!accepted.length} onClick={download}>
            <Roll>{`Download marked-up copy (${accepted.length})`}</Roll><span aria-hidden>↓</span>
          </button>
          <p className="mono mt-4 text-[10px] text-mute">Opens in your web browser. Not legal advice.</p>
        </div>
      </aside>
    </main>
  )
}
